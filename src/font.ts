export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

export function textWidth(s: string, scale = 1) {
  return s.length === 0 ? 0 : (s.length * ADVANCE - 1) * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  s: string,
  x: number,
  y: number,
  color: string,
  opts: { scale?: number; align?: 'left' | 'center' | 'right'; shadow?: string } = {},
) {
  const scale = opts.scale ?? 1;
  const w = textWidth(s, scale);
  let x0 = Math.round(opts.align === 'center' ? x - w / 2 : opts.align === 'right' ? x - w : x);
  const y0 = Math.round(y);
  if (opts.shadow) {
    drawRaw(ctx, s, x0 + scale, y0 + scale, opts.shadow, scale);
  }
  drawRaw(ctx, s, x0, y0, color, scale);
}

function drawRaw(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string, scale: number) {
  ctx.fillStyle = color;
  for (const ch of s) {
    const g = G[ch] ?? G[ch.toUpperCase()] ?? G[' '];
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (g.charCodeAt(r * GLYPH_W + c) === 49) ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
      }
    }
    x += ADVANCE * scale;
  }
}
