// Runs in the page.
async function convert({ url, opt, palette }) {
  const img = new Image();
  img.src = url;
  await img.decode();
  const W = img.naturalWidth, H = img.naturalHeight;
  const cv = new OffscreenCanvas(W, H);
  const cx = cv.getContext('2d');
  cx.drawImage(img, 0, 0);
  const px = cx.getImageData(0, 0, W, H).data;

  // background = average of the four corner patches
  let br = 0, bg = 0, bb = 0, n = 0;
  for (const [x0, y0] of [[0, 0], [W - 16, 0], [0, H - 16], [W - 16, H - 16]])
    for (let y = y0; y < y0 + 16; y++) for (let x = x0; x < x0 + 16; x++) {
      const i = (y * W + x) * 4; br += px[i]; bg += px[i + 1]; bb += px[i + 2]; n++;
    }
  br /= n; bg /= n; bb /= n;
  const thr = opt.bgThreshold ?? 110;
  const fg = new Uint8Array(W * H);
  for (let i = 0; i < W * H; i++) {
    const dr = px[i * 4] - br, dg = px[i * 4 + 1] - bg, db = px[i * 4 + 2] - bb;
    fg[i] = dr * dr + dg * dg + db * db > thr * thr ? 1 : 0;
  }

  // frames = connected blobs of foreground (8-connected). Big blobs are frames (left → right, or
  // top → bottom if stacked); small ones (an antler tip, a whisker) join the frame whose box is nearest.
  const lab = new Int32Array(W * H).fill(-1);
  const comps = [];
  const stack = [];
  for (let i0 = 0; i0 < W * H; i0++) {
    if (!fg[i0] || lab[i0] >= 0) continue;
    const id = comps.length, c = { n: 0, x0: W, x1: 0, y0: H, y1: 0 };
    lab[i0] = id; stack.push(i0);
    while (stack.length) {
      const i = stack.pop(), x = i % W, y = (i / W) | 0;
      c.n++; c.x0 = Math.min(c.x0, x); c.x1 = Math.max(c.x1, x + 1); c.y0 = Math.min(c.y0, y); c.y1 = Math.max(c.y1, y + 1);
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
        const xx = x + dx, yy = y + dy;
        if (xx < 0 || yy < 0 || xx >= W || yy >= H) continue;
        const j = yy * W + xx;
        if (fg[j] && lab[j] < 0) { lab[j] = id; stack.push(j); }
      }
    }
    comps.push(c);
  }
  const biggest = Math.max(...comps.map((c) => c.n));
  // a one-frame prop may be several pieces (a bench and its sign): then the biggest blob is the frame and the rest join it
  const frameIds = opt.frames === 1 ? [comps.findIndex((c) => c.n === biggest)] : comps.map((c, k) => k).filter((k) => comps[k].n > biggest * 0.2);
  const stacked = (() => {
    const fs = frameIds.map((k) => comps[k]);
    return fs.length > 1 && fs.every((a, i) => fs.every((b, j) => i === j || a.x1 <= b.x0 || b.x1 <= a.x0) ? false : true);
  })();
  frameIds.sort((a, b) => stacked ? comps[a].y0 - comps[b].y0 : comps[a].x0 - comps[b].x0);
  if (opt.frames && frameIds.length !== opt.frames) return { error: `found ${frameIds.length} frames, expected ${opt.frames}` };
  const owner = new Int32Array(comps.length).fill(-1); // comp → frame index
  frameIds.forEach((k, f) => (owner[k] = f));
  const gapTo = (c, d) => Math.max(0, d.x0 - c.x1, c.x0 - d.x1) + Math.max(0, d.y0 - c.y1, c.y0 - d.y1);
  comps.forEach((c, k) => {
    if (owner[k] >= 0 || c.n < 12) return; // specks of JPEG noise stay out
    let best = -1, bd = Infinity;
    frameIds.forEach((fk, f) => { const d = gapTo(c, comps[fk]); if (d < bd) { bd = d; best = f; } });
    if (bd < (opt.frames === 1 ? W / 4 : W / 25)) owner[k] = best;
  });
  const boxes = frameIds.map(() => ({ x0: W, x1: 0, y0: H, y1: 0 }));
  comps.forEach((c, k) => {
    const b = boxes[owner[k]];
    if (!b) return;
    b.x0 = Math.min(b.x0, c.x0); b.x1 = Math.max(b.x1, c.x1); b.y0 = Math.min(b.y0, c.y0); b.y1 = Math.max(b.y1, c.y1);
  });
  // a pixel belongs to frame f only if its blob does
  const inFrame = (i, f) => lab[i] >= 0 && owner[lab[i]] === f;
  const pad = opt.outline ? 2 : 0;
  const bodyH = opt.height - pad;
  // 'shared': frames stand on one ground line (the lowest feet), so a jump stays in the air
  const ground = Math.max(...boxes.map((b) => b.y1));
  const tall = opt.alignY === 'shared' ? Math.max(...boxes.map((b) => ground - b.y0)) : Math.max(...boxes.map((b) => b.y1 - b.y0));
  // `cell` (source px per sprite px) pins the scale, so several images of one character match; else fit `height`
  const cell = opt.cell ?? tall / bodyH;
  const gw = Math.ceil(Math.max(...boxes.map((b) => b.x1 - b.x0)) / cell);
  const gh = opt.cell ? Math.ceil(tall / cell) : bodyH;

  const pal = palette.map((p) => [p.r, p.g, p.b]);
  const nearest = (r, g, b) => {
    let best = 0, bd = Infinity;
    for (let k = 0; k < pal.length; k++) {
      const [pr, pg, pb] = pal[k];
      const rm = (r + pr) / 2, dr = r - pr, dg = g - pg, db = b - pb;
      const d = (2 + rm / 256) * dr * dr + 4 * dg * dg + (2 + (255 - rm) / 256) * db * db;
      if (d < bd) { bd = d; best = k; }
    }
    return best;
  };
  const allow = opt.colors ? new Set(opt.colors.map((c) => palette.findIndex((p) => p.name === c))) : null;
  const nearestAllowed = (r, g, b) => {
    if (!allow) return nearest(r, g, b);
    let best = -1, bd = Infinity;
    for (const k of allow) {
      const [pr, pg, pb] = pal[k];
      const rm = (r + pr) / 2, dr = r - pr, dg = g - pg, db = b - pb;
      const d = (2 + rm / 256) * dr * dr + 4 * dg * dg + (2 + (255 - rm) / 256) * db * db;
      if (d < bd) { bd = d; best = k; }
    }
    return best;
  };

  // own colours (`palette: false`): Grok's shades kept, near-identical ones merged into one flat colour
  // (JPEG noise); they get ids from 1000 up, the 32 game colours keep theirs
  const own = [];
  const ownId = (r, g, b) => {
    const tol = opt.merge ?? 20;
    let k = own.findIndex((q) => Math.hypot(q[0] - r, q[1] - g, q[2] - b) < tol);
    if (k < 0) { k = own.length; own.push([r, g, b]); }
    return 1000 + k;
  };
  // centre sampling: the colour is the median of the cell's middle half — not a vote over the whole cell,
  // which smears outlines and small features (eyes, bib) into their neighbours
  const centre = (sx0, sx1, sy0, sy1, b, f) => {
    const w = sx1 - sx0, h = sy1 - sy0;
    const rs = [], gs = [], bs = [];
    let all = 0;
    const ya = Math.floor(sy0 + h * 0.25), yb = Math.max(ya + 1, Math.ceil(sy0 + h * 0.75));
    const xa = Math.floor(sx0 + w * 0.25), xb = Math.max(xa + 1, Math.ceil(sx0 + w * 0.75));
    for (let y = ya; y < yb; y++)
      for (let x = xa; x < xb; x++) {
        if (x < b.x0 || x >= b.x1 || y < 0 || y >= H) continue;
        all++;
        const i = y * W + x;
        if (!inFrame(i, f)) continue;
        rs.push(px[i * 4]); gs.push(px[i * 4 + 1]); bs.push(px[i * 4 + 2]);
      }
    if (!all || rs.length / all < (opt.fill ?? 0.5)) return -1;
    const med = (a) => a.sort((u, v) => u - v)[a.length >> 1];
    const r = med(rs), g = med(gs), bl = med(bs);
    return opt.palette === false ? ownId(r, g, bl) : nearestAllowed(r, g, bl);
  };

  const grids = boxes.map((b, f) => {
    // anchor point of the grid in source pixels
    const gx0 = opt.alignX === 'left' ? b.x0 : opt.alignX === 'center' ? (b.x0 + b.x1) / 2 - (gw * cell) / 2 : b.x1 - gw * cell;
    const gy0 = opt.alignY === 'top' ? b.y0 : opt.alignY === 'center' ? (b.y0 + b.y1) / 2 - (gh * cell) / 2 : opt.alignY === 'shared' ? ground - gh * cell : b.y1 - gh * cell;
    const g = [];
    for (let cy = 0; cy < gh; cy++) {
      const row = [];
      for (let cxx = 0; cxx < gw; cxx++) {
        const sx0 = Math.floor(gx0 + cxx * cell), sx1 = Math.floor(gx0 + (cxx + 1) * cell);
        const sy0 = Math.floor(gy0 + cy * cell), sy1 = Math.floor(gy0 + (cy + 1) * cell);
        if (opt.sample === 'centre') { row.push(centre(sx0, sx1, sy0, sy1, b, f)); continue; }
        const votes = new Map();
        let on = 0, all = 0;
        for (let y = Math.max(0, sy0); y < Math.min(H, sy1); y++)
          for (let x = Math.max(b.x0, sx0); x < Math.min(b.x1, sx1); x++) {
            all++;
            const i = y * W + x;
            if (!inFrame(i, f)) continue;
            on++;
            const k = opt.palette === false ? ownId(px[i * 4], px[i * 4 + 1], px[i * 4 + 2]) : nearestAllowed(px[i * 4], px[i * 4 + 1], px[i * 4 + 2]);
            votes.set(k, (votes.get(k) ?? 0) + 1);
          }
        if (!all || on / all < (opt.fill ?? 0.45)) { row.push(-1); continue; }
        // the outline colour only wins a cell outright; otherwise the fill colour shows through
        // (ink = palette ink, or with own colours any near-black one — Grok's navy outline)
        const isInk = (k) => k === 0 || (k >= 1000 && own[k - 1000].reduce((u, v) => u + v, 0) < 150);
        let best = -1, bv = -1;
        for (const [k, v] of votes) {
          const w = isInk(k) && !opt.keepInk ? (v / on > 0.6 ? v : v * 0.5) : v;
          if (w > bv) { bv = w; best = k; }
        }
        // `detail`: a dark minority (eyes, mouth, seams) wins over a lighter majority, so a face keeps its
        // eyes when several source pixels squeeze into one (cells on the shape's edge are left to the vote)
        if (opt.detail && on / all > 0.95) {
          const lum = (k) => { const c = k >= 1000 ? own[k - 1000] : [palette[k].r, palette[k].g, palette[k].b]; return 0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2]; };
          const lb = lum(best);
          let dk = -1, dv = 0;
          for (const [k, v] of votes) if (v / on >= opt.detail && lum(k) < lb * 0.55 && v > dv) { dv = v; dk = k; }
          if (dk >= 0) best = dk;
        }
        row.push(best);
      }
      g.push(row);
    }
    return g;
  });

  // outline: 1 px of ink around the shape, outside it
  const final = grids.map((g) => {
    if (!opt.outline) return g;
    const h = g.length + 2, w = g[0].length + 2;
    const o = Array.from({ length: h }, (_, y) => Array.from({ length: w }, (_, x) => g[y - 1]?.[x - 1] ?? -1));
    const r = o.map((row) => row.slice());
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      if (o[y][x] >= 0) continue;
      if ([[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => (o[y + dy]?.[x + dx] ?? -1) >= 0)) r[y][x] = 0;
    }
    return r;
  });

  // trim columns that are empty in every frame
  const fw = final[0][0].length;
  const used = (x) => final.some((g) => g.some((row) => row[x] >= 0));
  let l = 0, rr = fw - 1;
  while (l < rr && !used(l)) l++;
  while (rr > l && !used(rr)) rr--;
  // and rows empty in every frame (from the top; the bottom row is the anchor)
  let top = 0;
  while (top < final[0].length - 1 && final.every((g) => g[top].every((k) => k < 0))) top++;
  const chars = 'abcdefghijklmnopqrstuvwxyzABCDEFGH';
  const keys = {}, charOf = new Map();
  const frames = final.map((g) => g.slice(top).map((row) => row.slice(l, rr + 1).map((k) => {
    if (k < 0) return '.';
    if (!charOf.has(k)) {
      const ch = chars[charOf.size] ?? String.fromCharCode(0x100 + charOf.size); // own colours can exceed 34
      charOf.set(k, ch);
      keys[ch] = k >= 1000 ? '#' + own[k - 1000].map((v) => v.toString(16).padStart(2, '0')).join('') : opt.remap?.[palette[k].name] ?? palette[k].name;
    }
    return charOf.get(k);
  }).join('')));
  return { frames, keys, cell: +cell.toFixed(2) };
}

function bigSheet({ out, cfg, palette }) {
  const ROWS = ['idle', 'walk', 'run', 'climb', 'descend', 'cheer', 'rest', 'sleep'];
  const BIG = 80, TRAIL = 40, TOP = BIG * ROWS.length;
  const cv = new OffscreenCanvas(BIG * 4, TOP + TRAIL * ROWS.length);
  const cx = cv.getContext('2d');
  const hex = Object.fromEntries(palette.map((p) => [p.name, p.hex]));
  const place = (a, cell, y0, used, id) => a.frames.forEach((f, j) => {
    const row = ROWS.indexOf(cfg[id].rows?.[j]);
    if (row < 0 || used[row] >= 4) return;
    const col = used[row]++;
    const w = f[0].length, h = f.length;
    if (w > cell || h > cell) throw new Error(`${id} frame ${j} is ${w}×${h}, bigger than the ${cell} px cell`);
    const ox = col * cell + Math.floor((cell - w) / 2), oy = y0 + row * cell + cell - h;
    f.forEach((r, y) => [...r].forEach((ch, x) => {
      if (ch === '.') return;
      cx.fillStyle = hex[a.keys[ch]] ?? a.keys[ch];
      cx.fillRect(ox + x, oy + y, 1, 1);
    }));
  });
  const usedBig = ROWS.map(() => 0), usedTrail = ROWS.map(() => 0);
  for (const [id, a] of Object.entries(out)) {
    place(a, BIG, 0, usedBig, id);
    if (a.trail) place(a.trail, TRAIL, TOP, usedTrail, id);
  }
  return cv.convertToBlob().then((b) => new Promise((r) => { const fr = new FileReader(); fr.onload = () => r(fr.result); fr.readAsDataURL(b); }));
}

function preview({ out, palette }) {
  const S = 8, P = 6;
  const items = Object.entries(out);
  const colW = Math.max(...items.map(([, a]) => a.frames[0][0].length)) + P;
  const rowH = Math.max(...items.map(([, a]) => a.frames[0].length)) + P;
  const nf = Math.max(...items.map(([, a]) => a.frames.length));
  const cv = new OffscreenCanvas((colW * nf * 2 + P) * S, (rowH * items.length + P) * S);
  const cx = cv.getContext('2d');
  const hex = Object.fromEntries(palette.map((p) => [p.name, p.hex]));
  cx.fillStyle = hex.green; cx.fillRect(0, 0, cv.width / 2, cv.height);
  cx.fillStyle = hex.night; cx.fillRect(cv.width / 2, 0, cv.width / 2, cv.height);
  items.forEach(([, a], i) => {
    for (const half of [0, 1]) a.frames.forEach((f, j) => {
      const ox = P + half * colW * nf + j * colW, oy = P + i * rowH + (rowH - P - f.length);
      f.forEach((row, y) => [...row].forEach((ch, x) => {
        if (ch === '.') return;
        cx.fillStyle = hex[a.keys[ch]] ?? a.keys[ch];
        cx.fillRect((ox + x) * S, (oy + y) * S, S, S);
      }));
    });
  });
  return cv.convertToBlob().then((b) => new Promise((r) => { const fr = new FileReader(); fr.onload = () => r(fr.result); fr.readAsDataURL(b); }));
}
