// Turns Grok Imagine sprite sheets (art/grok/<group>/*.jpg, frames side by side on a flat magenta
// background) into game-size, palette-exact char-map sprites, written to src/<group>art.ts.
//
// usage: node scripts/grok-sprites.mjs [group]      (default: wild)
//
// Per image (settings in art/grok/<group>/sprites.json):
//   1. key out the background (the colour in the corners),
//   2. split the frames on empty columns (left → right = frame order),
//   3. downscale each frame to `height` px: every output cell takes the most common palette colour
//      of its source pixels (nearest of the 32 game colours), or stays empty if it's mostly background,
//   4. all frames share one grid, anchored by `alignX` / `alignY` (default: right + bottom — the head
//      and feet stay put while the tail or legs move), so the animation doesn't jitter,
//   5. optional 1 px `ink` outline outside the shape (`outline`, default true; counts towards `height`).
// Colour of a cell: majority vote over the cell — best when shrinking a lot (animals, props: 30–80 source px
// per sprite px). `sample: 'centre'` takes the median of the cell's middle half instead — sharper faces and
// outlines when the cell is close to Grok's own pixel size (the big hero, ~1.5–2 Grok pixels per cell).
// Other settings: `frames` (expected count), `palette: false` (keep Grok's own colours, near ones merged
// within `merge`, default 20), `colors` (palette names allowed), `remap` ({ from: to } after
// snapping, e.g. to lift a whole sprite one shade), `fill` (share of a cell that must be foreground,
// default 0.45 — lower keeps thin antlers and legs), `idle` (frames looping while the animal sits).
// Also writes docs/sprites/<group>-preview.png (8×, on grass and on night) to eyeball the result.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { chromium } from 'playwright';

const group = process.argv[2] ?? 'wild';
// --big <out.png>: instead of src/<group>art.ts, make a character pack (src/bighero.ts): every image is
// converted twice — big (its `cell`, centre sampling, own colours; 80 px cells at the top) and trail size
// (`cell` × `trailScale`, default 2.35, majority vote + ink outline; 40 px cells below). Each image's `rows`
// says which animation row each of its frames goes to (idle, walk, run, climb, descend, cheer, rest, sleep).
const bigOut = process.argv.includes('--big') ? process.argv[process.argv.indexOf('--big') + 1] : null;
const dir = `art/grok/${group}`;
const cfg = JSON.parse(readFileSync(`${dir}/sprites.json`, 'utf8'));
const palette = JSON.parse(readFileSync('docs/palette.json', 'utf8')); // [{ name, hex, r, g, b }]
const files = readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f));

const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage();

const out = {};
for (const [id, opt] of Object.entries(cfg)) {
  const file = files.find((f) => f.replace(/\.[^.]+$/, '') === (opt.file ?? id));
  if (!file) { console.warn(`skip ${id}: no image`); continue; }
  const mime = /\.png$/i.test(file) ? 'image/png' : /\.webp$/i.test(file) ? 'image/webp' : 'image/jpeg';
  const url = `data:${mime};base64,${readFileSync(`${dir}/${file}`).toString('base64')}`;
  const base = { outline: true, alignX: 'right', alignY: 'bottom', ...opt };
  const res = await page.evaluate(convert, { url, opt: base, palette });
  if (res.error) { console.warn(`skip ${id}: ${res.error}`); continue; }
  if (bigOut) {
    const trailOpt = { ...base, cell: opt.cell * (opt.trailScale ?? 2.35), sample: 'vote', outline: true, fill: opt.trailFill ?? 0.45, detail: opt.trailDetail ?? 0.18 };
    res.trail = await page.evaluate(convert, { url, opt: trailOpt, palette });
    const tf = res.trail.frames[0];
    console.log(`  trail: ${tf[0].length}×${tf.length} px`);
  }
  if (opt.idle) res.idle = opt.idle;
  out[id] = res;
  console.log(`${id}: ${res.frames.length} frames, ${res.frames[0][0].length}×${res.frames[0].length} px, ${Object.keys(res.keys).length} colours, ${res.cell} src px/px`);
  delete res.cell;
}

if (bigOut) {
  const png = await page.evaluate(bigSheet, { out, cfg, palette });
  writeFileSync(bigOut, Buffer.from(png.split(',')[1], 'base64'));
  console.log(`wrote ${bigOut}`);
  await browser.close();
  process.exit(0);
}

// ---- src/<group>art.ts
const lines = [
  `// Generated by scripts/grok-sprites.mjs from art/grok/${group}/ (Grok Imagine). Do not edit by hand.`,
  `import { C } from './palette';`,
  ``,
  `export const ${group.toUpperCase()}_ART: Record<string, { frames: string[][]; keys: Record<string, string>; idle?: number }> = {`,
];
for (const [id, a] of Object.entries(out)) {
  lines.push(`  ${id}: {`);
  if (a.idle) lines.push(`    idle: ${a.idle},`);
  lines.push(`    keys: { ${Object.entries(a.keys).map(([k, n]) => `${k}: ${n.startsWith('#') ? `'${n}'` : `C.${n}`}`).join(', ')} },`);
  lines.push(`    frames: [`);
  for (const f of a.frames) lines.push(`      [\n${f.map((r) => `        '${r}',`).join('\n')}\n      ],`);
  lines.push(`    ],`);
  lines.push(`  },`);
}
lines.push(`};`, ``);
writeFileSync(`src/${group}art.ts`, lines.join('\n'));
console.log(`wrote src/${group}art.ts`);

// ---- preview sheet
const png = await page.evaluate(preview, { out, palette });
writeFileSync(`docs/sprites/${group}-preview.png`, Buffer.from(png.split(',')[1], 'base64'));
console.log(`wrote docs/sprites/${group}-preview.png`);
await browser.close();

